/**
 * Builds migrations/0005_certifiers_seed_bpjph.sql from the BPJPH list saved on 17 Oct 2026
 * (seed/certifiers/bpjph-lhln-2026-10-17.json). `pnpm exec tsx scripts/certifiers-seed-sql.ts` writes it;
 * `lib/certifiers/seed-sql.test.ts` fails if the committed file and the JSON drift apart.
 *
 * Every value comes from the official list. Nothing is invented: no websites or emails.
 */
import { BPJPH_AUTHORITY_ID, BPJPH_LIST_URL, BPJPH_SOURCE_ID, canonicalRowsJson, sha256Hex, toSourceRow, type BpjphRawRow } from "./bpjph";
import { certifierSlug, normaliseName } from "./names";
import { BPJPH_SCOPE_MAP, SCOPE_LABELS } from "./scopes";

/** 2026-10-17T10:00:00Z, when the seed list was read from the official site. */
export const SEED_CHECKED_AT = Date.UTC(2026, 9, 17, 10, 0, 0);
export const SEED_FILE = "seed/certifiers/bpjph-lhln-2026-10-17.json";
export const SEED_SNAPSHOT_ID = "bpjph-lhln-2026-10-17-seed";

export function sqlString(value: string | number | null | undefined): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${value.replace(/'/g, "''")}'`;
}

function values(...items: (string | number | null | undefined)[]): string {
  return `(${items.map(sqlString).join(", ")})`;
}

export const seedCertifierId = (row: BpjphRawRow) => row.lph_id.trim().toLowerCase();
export const seedRecognitionId = (row: BpjphRawRow) => `bpjph-${row.lph_id.trim().toLowerCase()}`;

export async function buildBpjphSeedSql(rows: readonly BpjphRawRow[]): Promise<string> {
  const at = SEED_CHECKED_AT;
  const slugs = new Set<string>();
  const aliases = new Set<string>();
  const hash = await sha256Hex(canonicalRowsJson(rows));
  const out: string[] = [
    "-- BPJPH's recognised foreign halal certification bodies, as listed on 17 Oct 2026. Additive: inserts only.",
    "--",
    `-- Generated by scripts/certifiers-seed-sql.ts from ${SEED_FILE} (${rows.length} rows, read from`,
    `-- ${BPJPH_LIST_URL} at 2026-10-17T10:00:00Z). Do not edit by hand: change the script and regenerate.`,
    "-- INSERT OR IGNORE keeps it safe to re-run. BPJPH's status word ('MRA') is kept in source_status.",
    "",
    `INSERT OR IGNORE INTO "cert_authority" ("id", "name", "short_name", "country_codes", "website", "notes_md", "updated_at") VALUES`,
    `  ${values(BPJPH_AUTHORITY_ID, "Badan Penyelenggara Jaminan Produk Halal", "BPJPH", '["ID"]', "https://bpjph.halal.go.id", null, at)};`,
    "",
    `INSERT OR IGNORE INTO "cert_source" ("id", "authority_id", "url", "kind", "parser", "active", "last_checked_at", "last_ok_at", "last_error", "needs_look") VALUES`,
    `  ${values(BPJPH_SOURCE_ID, BPJPH_AUTHORITY_ID, BPJPH_LIST_URL, "html_table", "bpjph_lhln", 1, at, at, null, 0)};`,
    "",
    `INSERT OR IGNORE INTO "scope" ("code", "label") VALUES`,
    Object.entries(SCOPE_LABELS)
      .map(([code, label]) => `  ${values(code, label)}`)
      .join(",\n") + ";",
    "",
    `INSERT OR IGNORE INTO "scope_map" ("authority_id", "raw", "scope_code") VALUES`,
    Object.entries(BPJPH_SCOPE_MAP)
      .map(([raw, code]) => `  ${values(BPJPH_AUTHORITY_ID, raw, code)}`)
      .join(",\n") + ";",
    "",
    `INSERT OR IGNORE INTO "cert_snapshot" ("id", "source_id", "fetched_at", "http_status", "content_hash", "r2_key", "row_count", "parse_ok", "error") VALUES`,
    `  ${values(SEED_SNAPSHOT_ID, BPJPH_SOURCE_ID, at, 200, hash, SEED_FILE, rows.length, 1, null)};`,
  ];

  for (const raw of rows) {
    const row = toSourceRow(raw);
    const slug = certifierSlug(row.name);
    const alias = normaliseName(row.name);
    if (slugs.has(slug)) throw new Error(`Duplicate slug ${slug}`);
    if (aliases.has(alias)) throw new Error(`Duplicate alias ${alias}`);
    slugs.add(slug);
    aliases.add(alias);
    const certifierId = seedCertifierId(raw);
    out.push(
      "",
      `-- ${row.name.replace(/[\r\n]+/g, " ")}`,
      `INSERT OR IGNORE INTO "certifier" ("id", "slug", "name", "country_code", "city", "address", "created_at", "updated_at") VALUES`,
      `  ${values(certifierId, slug, row.name, row.countryCode, row.city, row.address, at, at)};`,
      `INSERT OR IGNORE INTO "certifier_alias" ("certifier_id", "alias_norm", "authority_id") VALUES ${values(certifierId, alias, BPJPH_AUTHORITY_ID)};`,
      `INSERT OR IGNORE INTO "recognition" ("id", "certifier_id", "authority_id", "status", "scopes", "scopes_raw", "source_ref", "source_key", "source_status", "valid_from", "valid_until", "first_seen_at", "last_seen_at", "last_checked_at", "updated_at", "source_id") VALUES`,
      `  ${values(
        seedRecognitionId(raw),
        certifierId,
        BPJPH_AUTHORITY_ID,
        "recognised",
        JSON.stringify(row.scopes),
        row.scopesRaw,
        row.sourceRef,
        row.sourceKey,
        row.sourceStatus,
        null,
        row.validUntil,
        at,
        at,
        at,
        at,
        BPJPH_SOURCE_ID,
      )};`,
    );
  }
  return out.join("\n") + "\n";
}
